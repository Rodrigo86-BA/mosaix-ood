"""Table 2: multi-instance coverage (objects lit) and mosaic AUROC.

experiment_name = 'camera_ready_tables'
dataset_name    = 'imagenet1k (ImageNet-S300 val) + Table 1'

WHAT THE TABLE COMBINES (nothing is re-run)
-------------------------------------------
ID side, localization (working-repo scripts cr_205/cr_207, RN-50 CE trained
from scratch, the network of Table 1):
  363 ImageNet-S300 val images, correctly classified, with >=2 objects of the
  class (connected component of the mask covering >=1% of the crop).
    B/multi  frac_lit   fraction of objects lit (map maximum inside the
                        object >= 0.5 of the global maximum, the delta=0.5 of
                        Grad-CAM++)
    B/multi  all_lit    all objects lit
    E2/multi PG15       pointing game (map maximum inside the mask,
                        15 px tolerance)
OOD side, evidence (frozen CSV of scripts/76 via cr_209/cr_207_link):
    mean query s on ID and far-OOD; near/far AUROC of Table 1.
Marks: 95% bootstrap CI of the paired difference against GradCAM
(vs_cam_diff_lo/hi of cr_207): above zero -> \blacktriangle, below ->
\blacktriangledown.

The paper table keeps only the fraction of objects lit and the near/far
AUROC; all_lit, the pointing game and the mean s are still computed and go to
the companion.

Inputs:
  results/camera_ready_localization/cr_207_scope_summary.csv
  results/camera_ready_localization/cr_207_link.csv
Outputs:
  results/camera_ready_tables/tab_multiinst.tex
  results/camera_ready_tables/cr_214_multiinst.txt  (companion)

Usage:
  $PYTHON_BIN camera_ready_code/tab2_multiinstance.py
"""
import os

experiment_name = "camera_ready_tables"
dataset_name    = "imagenet1k"

from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
ROOT = Path(os.environ.get("MOSAIX_ROOT", REPO))
LOC = ROOT / "results" / "camera_ready_localization"
OUT = ROOT / "results" / experiment_name
OUT.mkdir(parents=True, exist_ok=True)
METH = [("cam", "GradCAM"), ("gradcampp", "GradCAM\\texttt{++}"), ("scorecam", "ScoreCAM")]


def main():
    sc = pd.read_csv(LOC / "cr_207_scope_summary.csv")
    lk = pd.read_csv(LOC / "cr_207_link.csv")

    def loc(regime, metric, m):
        r = sc[(sc.regime == regime) & (sc.metric == metric) & (sc.method == m)].iloc[0]
        mark = ""
        if m != "cam":
            if r.vs_cam_diff_lo > 0:
                mark = r"\,$\blacktriangle$"
            elif r.vs_cam_diff_hi < 0:
                mark = r"\,$\blacktriangledown$"
        return r["mean"], mark, int(r.n)

    def link(col, m):
        return float(lk[lk.method == m][col].iloc[0])

    rows_loc = [("Objects lit (fraction) $\\uparrow$", "B/multi", "frac_lit"),
                ("All objects lit $\\uparrow$", "B/multi", "all_lit"),
                ("Pointing game $\\uparrow$", "E2/multi", "PG15")]
    vals = {}
    lines = []
    for name, reg, met in rows_loc:
        cells = []
        best = max(loc(reg, met, m)[0] for m, _ in METH)
        for m, _ in METH:
            v, mk, n = loc(reg, met, m)
            vals[(met, m)] = (v, n)
            s = f"{v:.3f}".lstrip("0")
            cells.append((f"\\textbf{{{s}}}" if abs(v - best) < 1e-12 else s) + mk)
        lines.append(name + " & " + " & ".join(cells) + r" \\")
    ev = []
    for name, col, hib in [("Mean $s$, ID", "s_id", None),
                           ("Mean $s$, far-OOD $\\downarrow$", "s_far", False),
                           ("AUROC near $\\uparrow$", "auroc_near", True),
                           ("AUROC far $\\uparrow$", "auroc_far", True)]:
        v = {m: link(col, m) for m, _ in METH}
        vals[(col, "all")] = v
        best = None if hib is None else (max if hib else min)(v.values())
        cells = []
        for m, _ in METH:
            s = f"{v[m]:.3f}".lstrip("0")
            cells.append(f"\\textbf{{{s}}}" if best is not None and abs(v[m] - best) < 1e-12 else s)
        ev.append(name + " & " + " & ".join(cells) + r" \\")
    n_multi = vals[("frac_lit", "cam")][1]
    # Paper table: only the fraction of objects lit and near/far AUROC.
    # all_lit, pointing game and mean s are still computed and go to the
    # companion.
    lines_tex = [l for l in lines if l.startswith("Objects lit")]
    ev_tex = [l for l in ev if l.startswith("AUROC")]

    tex = "\n".join([
        "% generated by camera_ready_code/tab2_multiinstance.py -- do not edit by hand",
        r"\begin{table}[t]",
        r"\centering\small",
        r"\caption{Objects lit on ImageNet-S images with two or more objects of the class, and AUROC of the mosaic "
        r"(Table~\ref{tab:saliency}). An object is lit when the map maximum inside it reaches half of the global maximum. "
        r"$\blacktriangle$: above GradCAM (95\% CI).}",
        r"\label{tab:multiinst}",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\columnwidth}{!}{%",
        r"\begin{tabular}{@{}lccc@{}}",
        r"\toprule",
        " & " + " & ".join(l for _, l in METH) + r" \\",
        r"\midrule",
        rf"\multicolumn{{4}}{{@{{}}l}}{{\emph{{ID, $\geq$2 objects ($n={n_multi}$)}}}} \\",
        *lines_tex,
        r"\midrule",
        r"\multicolumn{4}{@{}l}{\emph{Mosaic, $n=1000$ per set}} \\",
        *ev_tex,
        r"\bottomrule",
        r"\end{tabular}}",
        r"\end{table}",
    ])
    (OUT / "tab_multiinst.tex").write_text(tex + "\n")

    txt = ["(1) Script: camera_ready_code/tab2_multiinstance.py",
           "(2) What it measures: ID side = coverage of several objects and pointing game on the",
           "    ImageNet-S images with >=2 objects; OOD side = mean s and AUROC of the mosaic (Table 1).",
           "(3) Files: tab_multiinst.tex.",
           "(4) Numbers:"]
    for (k, m), v in vals.items():
        txt.append(f"    {k:12s} {m:10s} {v}")
    txt += ["(5) Guide:",
            "  1. Higher frac_lit/all_lit with an up arrow: the method covers more objects.",
            "  2. Pointing game with a down arrow: the map MAXIMUM falls on an object less",
            "     often; the advantage of the methods is coverage, not the position of the maximum.",
            "  3. Higher far-OOD s = more class energy on queries without the class",
            "     ('hallucinated evidence'); it goes with a lower AUROC."]
    (OUT / "cr_214_multiinst.txt").write_text("\n".join(txt) + "\n")
    print("\n".join(txt))
    print(tex)


if __name__ == "__main__":
    main()
