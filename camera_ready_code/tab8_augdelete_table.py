"""Table 8 (AugDelete): torchvision V2 and own mixup, original head versus refit.

experiment_name = 'camera_ready_augdelete'
dataset_name    = 'imagenet1k'

Sources (nothing is run here):
  V2     results/depth_sweep/64_auroc_tvV2_rn50_fullsample_20260909-0036.csv (ckpt, scripts/64)
         results/camera_ready_augdelete/auroc__v2_refitsgd_fullsample.csv (refit, tab8_augdelete_eval.py)
         (the earlier AdamW refit is 64_auroc_tvV2_augdelete_..._0123.csv; it overfits and
          was replaced by the SGD head of tab8_refit_head_sgd.py)
  (LS is measured by tab8_augdelete_eval.py and quoted in the text, not shown in the table.)
  mixup  results/camera_ready_augdelete/auroc__mixup_{ckpt,refitsgd}_fullsample.csv (tab8_augdelete_eval.py)
MosAIx-OOD = the 4x+tau readout (query in the 4 positions, class threshold).
near = SSB-hard, NINCO; far = iNaturalist, OpenImage-O, Textures.

GATE: n_ood of the evaluation runs = the full set (49000/5878/10000/17632/5640).

Outputs (results/camera_ready_augdelete/ of $MOSAIX_ROOT):
  tab_augdelete.tex, cr_218_summary.csv, cr_218_summary.txt (companion)

Usage:
  $PYTHON_BIN camera_ready_code/tab8_augdelete_table.py
"""
import os

experiment_name = "camera_ready_augdelete"
dataset_name    = "imagenet1k"

from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
ROOT = Path(os.environ.get("MOSAIX_ROOT", REPO))
RES = ROOT / "results" / experiment_name
DS = ROOT / "results" / "depth_sweep"
NEAR = ["ssb_hard", "ninco"]
FULL = {"ssb_hard": 49000, "ninco": 5878, "inaturalist": 10000, "openimage_o": 17632, "textures": 5640}
DET = [("mosXai-OOD-4x+tau", r"\method"), ("MLS", "MLS")]
MODELS = [
    ("V2", "torchvision V2", DS / "64_auroc_tvV2_rn50_fullsample_20260909-0036.csv",
     RES / "auroc__v2_refitsgd_fullsample.csv"),
    ("mixup", "Mixup (ours)", RES / "auroc__mixup_ckpt_fullsample.csv", RES / "auroc__mixup_refitsgd_fullsample.csv"),
]


def means(p):
    d = pd.read_csv(p)
    if "n_ood" in d:
        assert all(FULL[g] == n for g, n in zip(d.group, d.n_ood)), p.name
    top1 = float(d.top1.iloc[0])
    d["reg"] = d.group.map(lambda g: "near" if g in NEAR else "far")
    return d.groupby(["detector", "reg"]).auroc.mean().unstack(), top1


miss = [p.name for _, _, a, b in MODELS for p in (a, b) if not p.exists()]
if miss:
    raise SystemExit(f"missing: {miss} -- nothing was written")

rows, body = [], []
f3 = lambda v: f"{v:.3f}".replace("0.", ".", 1)
for key, lab, pa, pb in MODELS:
    (A, ta), (B, tb) = means(pa), means(pb)
    body.append(rf"\multicolumn{{5}}{{@{{}}l}}{{\emph{{{lab}}}}} \\")
    for d, name in DET:
        c = [A.near[d], B.near[d], A.far[d], B.far[d]]
        body.append(rf"\quad {name} & {f3(c[0])} & \textcolor{{rktwo}}{{{f3(c[1])}}} & "
                    rf"{f3(c[2])} & \textcolor{{rktwo}}{{{f3(c[3])}}} \\")
        rows.append(dict(model=key, detector=d, near_ckpt=c[0], near_refit=c[1], d_near=c[1] - c[0],
                         far_ckpt=c[2], far_refit=c[3], d_far=c[3] - c[2], top1_ckpt=ta, top1_refit=tb))
tex = "\n".join([
    "% generated by camera_ready_code/tab8_augdelete_table.py -- do not edit by hand",
    r"\begin{table}[t]\centering",
    r"\caption{Original head (ckpt) and AugDelete (refit) for two ResNet-50 models on ImageNet-1K. "
    r"AUROC ($\uparrow$), all images of each set.}\label{tab:augdelete}",
    r"\footnotesize\setlength{\tabcolsep}{3.4pt}",
    r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
    r" & \multicolumn{2}{c}{near-OOD} & \multicolumn{2}{c}{far-OOD} \\",
    r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
    r"Detector & ckpt & refit & ckpt & refit \\", r"\midrule",
    *body, r"\bottomrule", r"\end{tabular}", r"\end{table}"])
(RES / "tab_augdelete.tex").write_text(tex + "\n")
S = pd.DataFrame(rows)
S.to_csv(RES / "cr_218_summary.csv", index=False)
txt = f"""(1) Script: camera_ready_code/tab8_augdelete_table.py (measurements: scripts/64 for V2 ckpt, tab8_augdelete_eval.py for the rest).
(2) What it measures: near/far AUROC of MosAIx-OOD (4x+tau) and of MLS with the original head (ckpt) and
    with the linear head refit with CE on the same features (refit, AugDelete).
(3) Files: tab_augdelete.tex (paper table), cr_218_summary.csv.
(4) Numbers:
{S.round(4).to_string(index=False)}
(5) Guide:
  1. d_near/d_far > 0: the refit (CE, SGD 0.1, 50 epochs) improves detection for that detector on that model.
  2. top1_refit < top1_ckpt: accuracy cost of the refit. The refit recipe is the same on the three models;
     the ID of V2 is the raw tree and that of the own models is clean/val.
  3. Compare within a model (ckpt against refit); across models the ID also changes.
"""
(RES / "cr_218_summary.txt").write_text(txt)
print(txt)
print(tex)
