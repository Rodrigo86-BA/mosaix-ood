def f3(x, bold=False, dag=False):
    if not np.isfinite(x):
        return "--"
    s = f"{x:.3f}"
    if dag:
        s += r"$^\dagger$"
    return rf"\textbf{{{s}}}" if bold else s


def write(name, body):
    (OUT / name).write_text(BANNER + body)
    print(f"wrote paper/tables/{name}")


