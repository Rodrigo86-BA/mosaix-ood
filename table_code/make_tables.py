def block_rows(df, key_col, key_order, key_lab, models=None):
    """near/far means per recipe for each key of one ablation family."""
    rows = []
    for k in key_order:
        cells = []
        for m in (models or MODELS):
            d = df[(df.model == m) & (df[key_col] == k)].set_index("ood").auroc
            cells += [f3(d.get("_mean_near", np.nan)), f3(d.get("_mean_far", np.nan))]
        rows.append((key_lab[k], cells))
    return rows


