def tab1(metric, fname, caption, label, higher_better):
    cols = SETS + ["_mean_near", "_mean_far"]
    head = (r"\begin{table*}[t]\centering\caption{" + caption + r"}\label{" + label
            + "}\n" + r"\footnotesize\setlength{\tabcolsep}{4pt}"
            + r"\begin{tabular}{ll" + "c" * len(cols) + "}\n\\toprule\n"
            + " & & " + " & ".join([SET_LAB[s] for s in SETS])
            + r" & near & far \\" + "\n"
            + " & & \\multicolumn{2}{c}{near-OOD} & \\multicolumn{3}{c}{far-OOD}"
            + r" & mean & mean \\" + "\n\\midrule\n")
    body = ""
    for m in MODELS:
        dm = t1[t1.model == m].set_index(["detector", "ood"])[metric]
        vals = {(d, o): dm.get((d, o), np.nan) for d in DET_ORDER for o in cols}
        best = {}
        for o in cols:
            col = [vals[(d, o)] for d in DET_ORDER]
            best[o] = (np.nanmax(col) if higher_better else np.nanmin(col))
        for i, d in enumerate(DET_ORDER):
            lead = (rf"\multirow{{{len(DET_ORDER)}}}{{*}}{{{MLAB[m]}}}"
                    if i == 0 else "")
            cells = []
            for o in cols:
                v = vals[(d, o)]
                dag = (d == "dom_proto" and o in SETS and (m, o) in sig_set)
                cells.append(f3(v, bold=np.isclose(v, best[o]), dag=dag))
            body += lead + " & " + DET_LAB[d] + " & " + " & ".join(cells) + r" \\" + "\n"
        body += "\\midrule\n" if m != MODELS[-1] else ""
    tail = "\\bottomrule\n\\end{tabular}\n\\end{table*}\n"
    write(fname, head + body + tail)


def tab1_ce(metric, fname, caption, label, higher_better):
    """CE only: the most common recipe is the headline, the rest become robustness.

    A lean ordering: no rMaha, no ReAct, no kNN exemplar row and no delta columns
    against max-logit. The comparison stays in the means, which are already in the
    table."""
    order = ["MSP", "MLS", "Energy", "Maha", "KNN_k50", "ViM",
             "GradNorm", "GAIA-A", "GAIA-Z", "dom_proto"]
    DASH_BEFORE = "GradNorm"
    cols = SETS + ["_mean_near", "_mean_far"]
    full = ROOT / "results" / "full_panel_in1k" / "auroc__completo.csv"
    src, is_full = t1[t1.model == "ce"], False
    if full.exists() and metric == "auroc":
        f = pd.read_csv(full)
        f["detector"] = f.detector.map({"kNN": "KNN_k50",
                                        "mosXai-OOD": "dom_proto"}).fillna(
                                            f.detector)
        rows = []
        for r in f.itertuples():
            for o in SETS:
                rows.append(dict(model="ce", detector=r.detector, ood=o,
                                 auroc=getattr(r, "au_" + o)))
            rows.append(dict(model="ce", detector=r.detector,
                             ood="_mean_near", auroc=r.near))
            rows.append(dict(model="ce", detector=r.detector,
                             ood="_mean_far", auroc=r.far))
        src, is_full = pd.DataFrame(rows), True
    else:
        gp = ROOT / "results" / "gaia_table1" / "auroc__ce.csv"
        if gp.exists() and metric == "auroc":
            g = pd.read_csv(gp)
            g["detector"] = g.detector.map({"gaia_a": "GAIA-A",
                                            "gaia_z": "GAIA-Z",
                                            "gradnorm": "GradNorm"})
            src = pd.concat([src, g], ignore_index=True)
    sg = sig_set
    mp = ROOT / "results" / "bigpool_margin" / "margin_vs_mls.csv"
    if is_full and mp.exists():
        _m = pd.read_csv(mp)
        sg = {(r.model, r.ood) for r in _m.itertuples() if r.significant}
    dm = src.set_index(["detector", "ood"])[metric]
    vals = {(d, o): dm.get((d, o), np.nan) for d in order for o in cols}
    best = {o: (np.nanmax([vals[(d, o)] for d in order]) if higher_better
                else np.nanmin([vals[(d, o)] for d in order])) for o in cols}
    head = (r"\begin{table*}[t]\centering\caption{" + caption + r"}\label{" + label
            + "}\n" + r"\footnotesize\setlength{\tabcolsep}{5pt}"
            + r"\begin{tabular}{l" + "c" * len(cols) + "}\n\\toprule\n"
            + " & " + " & ".join([SET_LAB[x] for x in SETS])
            + r" & near & far \\" + "\n"
            + " & \\multicolumn{2}{c}{near-OOD} & \\multicolumn{3}{c}{far-OOD}"
            + r" & mean & mean \\" + "\n\\midrule\n")
    body = ""
    for d in order:
        if d == DASH_BEFORE:
            body += "\\addlinespace[2pt]\\hdashline\\addlinespace[2pt]\n"
        cells = [f3(vals[(d, o)], bold=np.isclose(vals[(d, o)], best[o]),
                    dag=(d == "dom_proto" and o in SETS and ("ce", o) in sg))
                 for o in cols]
        body += DET_LAB[d] + " & " + " & ".join(cells) + r" \\" + "\n"
    note = (r"\par\smallskip{\footnotesize $\dagger$ = paired-bootstrap "
            r"difference from MLS significant at 95\%.}" + "\n")
    write(fname, head + body + "\\bottomrule\n\\end{tabular}\n"
          + note + "\\end{table*}\n")


